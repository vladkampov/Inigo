#!/usr/bin/env python3
"""Independent mobile SemVer; app and extension consume one generated xcconfig."""
import pathlib, sys
from version import validate
root = pathlib.Path(__file__).resolve().parent.parent / 'Mobile'
version = validate((root / 'VERSION').read_text().strip())
build = (root / 'BUILD_NUMBER').read_text().strip()
if not build.isdigit() or not 0 < int(build) < 10000:
    raise ValueError('Mobile build must be an increasing integer from 1 to 9999')
expected = f'// Generated by scripts/mobile-version.py. Do not edit.\nMARKETING_VERSION = {version.split("-")[0].split("+")[0]}\nCURRENT_PROJECT_VERSION = {build}\nINIGO_DISPLAY_VERSION = {version}\n'
file = root / 'Version.xcconfig'
if '--check' in sys.argv:
    if file.read_text() != expected: raise ValueError('Run python3 scripts/mobile-version.py')
else: file.write_text(expected)
print(f'iOS {version} ({build})')
