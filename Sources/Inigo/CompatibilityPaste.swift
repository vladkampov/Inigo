import AppKit
import CoreGraphics
import InigoCore

/// A one-shot clipboard transaction, created only for an explicitly invoked rewrite.
/// No clipboard polling or history. All captured representations remain in memory.
@MainActor
final class CompatibilityPaste {
    private let pasteboard: NSPasteboard
    private let saved: [[NSPasteboard.PasteboardType: Data]]
    private let capturedChangeCount: Int
    private var ownedChangeCount: Int?
    private let ownershipType = NSPasteboard.PasteboardType("app.inigo.temporary-owner")
    private let ownershipID = UUID().uuidString

    init(pasteboard: NSPasteboard = .general) throws {
        self.pasteboard = pasteboard
        capturedChangeCount = pasteboard.changeCount
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        var sizes: [Int] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var representations: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else {
                    throw InigoError.message("The existing clipboard cannot be safely preserved. Use Copy rewrite instead.")
                }
                sizes.append(data.count)
                guard ClipboardPolicy.canSnapshot(sizes: sizes) else {
                    throw InigoError.message("The clipboard is too large to preserve safely. Use Copy rewrite instead.")
                }
                representations[type] = data
            }
            items.append(representations)
        }
        guard pasteboard.changeCount == capturedChangeCount else {
            throw InigoError.message("The clipboard changed. Nothing was pasted; try again.")
        }
        saved = items
    }

    func insert(_ text: String, into pid: pid_t) throws {
        guard let down = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: true),
              let up = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: false) else {
            throw InigoError.message("The Paste command could not be prepared.")
        }
        try stage(text)
        // Target this process only, not whichever app might become frontmost next.
        // This sends Cmd-V, never Return or a submit action.
        down.flags = .maskCommand; up.flags = .maskCommand
        down.postToPid(pid); up.postToPid(pid)
    }

    /// Separate staging permits isolated pasteboard tests without synthesizing input.
    func stage(_ text: String) throws {
        guard pasteboard.changeCount == capturedChangeCount else {
            throw InigoError.message("The clipboard changed. Nothing was pasted; try again.")
        }
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString(ownershipID, forType: ownershipType)
        // Honored by many clipboard managers; not a guarantee that none will retain the text.
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: .init(marker))
        }
        ownedChangeCount = pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            restore()
            throw InigoError.message("The temporary clipboard could not be prepared. Nothing was pasted.")
        }
        ownedChangeCount = pasteboard.changeCount
        guard pasteboard.string(forType: ownershipType) == ownershipID else {
            throw InigoError.message("The clipboard changed before pasting. Nothing was pasted.")
        }
    }

    func restore() {
        guard let ownedChangeCount, pasteboard.string(forType: ownershipType) == ownershipID,
              ClipboardPolicy.shouldRestore(ownedChangeCount: ownedChangeCount, currentChangeCount: pasteboard.changeCount) else { return }
        var items: [NSPasteboardItem] = []
        for representations in saved {
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: type) }
            items.append(item)
        }
        pasteboard.clearContents()
        if !items.isEmpty { pasteboard.writeObjects(items) }
        self.ownedChangeCount = nil
    }
}
